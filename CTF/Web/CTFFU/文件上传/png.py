# ---------- PNG 生成工具 ----------
def png_chunk(kind, data):
    chunk = kind + data
    return struct.pack(">I", len(data)) + chunk + struct.pack(">I", zlib.crc32(chunk) & 0xFFFFFFFF)


def save_png(path, width, height, pixels, tEXt_entries=None):
    """
    将 RGB 像素数据保存为 PNG 文件。
    tEXt_entries: 可选的 [(keyword, text), ...] 列表，会被写入 tEXt 块。
    """
    # 过滤行数据（每行开头加一个 filter byte 0x00）
    raw_rows = []
    for y in range(height):
        row = bytearray([0])  # filter type 0 (None)
        for x in range(width):
            row.extend(pixels[y][x])
        raw_rows.append(bytes(row))

    raw_data = b"".join(raw_rows)
    idat_data = zlib.compress(raw_data)

    png = b"\x89PNG\r\n\x1a\n"
    # 头块 IHDR：width, height, bit depth=8, color type=2(RGB), compression/filter/interlace 都为 0
    png += png_chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0))

    # 可选的 tEXt 块 —— 这就是“文件内容层面的写入”
    if tEXt_entries:
        for keyword, text in tEXt_entries:
            # tEXt 数据：keyword (1-79 bytes) + \x00 + text
            kw_bytes = keyword.encode("latin-1", errors="replace")[:79]
            txt_bytes = text.encode("latin-1", errors="replace")
            chunk_data = kw_bytes + b"\x00" + txt_bytes
            png += png_chunk(b"tEXt", chunk_data)

    png += png_chunk(b"IDAT", idat_data)
    png += png_chunk(b"IEND", b"")

    with open(path, "wb") as f:
        f.write(png)


# ---------- 文字 -> 像素 ----------
def text_to_pixels(text: str, scale: int = 1):
    """
    将多行文本转换为 RGB 像素数组 (list of list of (R,G,B))。
    字符用黑色 (#000)，背景为白色 (#FFF)。
    scale: 放大倍数 (默认 1，即 5x7 点阵原始大小)。
    """
    lines = text.splitlines()
    if not lines:
        lines = [""]

    char_width = 5
    char_height = 7
    spacing = 1  # 字符间距
    line_spacing = 1  # 行间距

    # 计算画布尺寸（单位：原始点阵像素）
    max_chars = max(len(line) for line in lines)
    canvas_w = max_chars * (char_width + spacing) - spacing if max_chars > 0 else 0
    canvas_h = len(lines) * (char_height + line_spacing) - line_spacing

    # 创建白色背景
    pixels_raw = [[(255, 255, 255) for _ in range(canvas_w)] for _ in range(canvas_h)]

    for row_idx, line in enumerate(lines):
        base_y = row_idx * (char_height + line_spacing)
        for col_idx, ch in enumerate(line):
            if ch not in FONT:
                ch = "?"
            glyph = FONT[ch]
            base_x = col_idx * (char_width + spacing)
            for gy in range(char_height):
                for gx in range(char_width):
                    if glyph[gy][gx] == "1":
                        y = base_y + gy
                        x = base_x + gx
                        if 0 <= y < canvas_h and 0 <= x < canvas_w:
                            pixels_raw[y][x] = (0, 0, 0)  # 黑色

    # 如果 scale > 1，则做最近邻放大
    if scale == 1:
        return pixels_raw, canvas_w, canvas_h

    scaled_w = canvas_w * scale
    scaled_h = canvas_h * scale
    scaled_pixels = [[(255, 255, 255) for _ in range(scaled_w)] for _ in range(scaled_h)]
    for y in range(canvas_h):
        for x in range(canvas_w):
            color = pixels_raw[y][x]
            for dy in range(scale):
                for dx in range(scale):
                    scaled_pixels[y * scale + dy][x * scale + dx] = color
    return scaled_pixels, scaled_w, scaled_h


# ---------- 主程序 ----------
def main():
    # 获取要说的话：命令行参数或交互输入
    if len(sys.argv) > 1:
        message = " ".join(sys.argv[1:])
    else:
        message = input("请输入你“要说的话”：\n> ")

    if not message.strip():
        print("没有输入文字，退出。")
        sys.exit(0)

    # 生成像素
    pixels, width, height = text_to_pixels(message, scale=2)  # 2倍放大更清晰

    # 准备 tEXt 块内容
    tEXt_entries = [
        ("Title", "My Message Image"),
        ("Message", message),
        ("Created", datetime.now().isoformat()),
    ]

    # 输出文件名
    out_path = Path("my_message.png")
    save_png(out_path, width, height, pixels, tEXt_entries)
    print(f"✅ 图片已生成：{out_path.resolve()}")
    print(f"   图片尺寸：{width}×{height} 像素")
    print(f"   消息已写入 tEXt 块：{message}")


if __name__ == "__main__":
    main()